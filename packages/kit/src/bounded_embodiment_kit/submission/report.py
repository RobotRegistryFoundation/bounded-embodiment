@dataclass
class Run:
    """The runner's run directory, as `be run` left it."""

    path: Path
    declared: dict
    test: str
    simulation: bool
    run_mode: str

    @classmethod
    def load(cls, path: str | Path) -> Run:
        root = Path(path)
        if not root.is_dir():
            raise Refused(f"{root} is not a run directory")
        declared = _json(_read(root / "declared.json", "the run's"), "declared.json")
        if not isinstance(declared, dict) or declared.get("format") != DECLARED_FORMAT:
            raise Refused(f"{root}/declared.json is not {DECLARED_FORMAT} (written by `be run`)")
        end = declared.get("end")
        if not isinstance(end, Mapping):
            raise Refused("declared.json has no end block: the runner did not finish writing the run")
        if not end.get("started"):
            raise Refused(f"the run never started ({end.get('status')}: {end.get('why')}); "
                          "nothing was sent, so there is nothing to report")
        test = TESTS.get(str(declared.get("test")).lower())
        if test is None:
            raise Refused(f"declared.json names test {declared.get('test')!r}; be report knows "
                          f"{', '.join(TESTS)}")
        return cls(root, declared, test, bool(declared.get("simulation")),
                   str(declared.get("run_mode", "")))


def generator_block(gen: object) -> dict:
    """The report's declared generator from declared.json's: the runner's control block becomes
    be-control/1 (seed 0: the control stream has no randomness and the runner records none)."""
    if not isinstance(gen, Mapping):
        raise Refused("declared.json has no generator block")
    name = gen.get("name")
    if name == "control":
        try:
            params = {"target": gen["target_id"], "seconds": gen["seconds"], "hz": gen["hz"],
                      "step_cap": gen["step_cap"], "start": gen.get("start")}
        except KeyError as e:
            raise Refused(f"declared.json's control generator has no {e.args[0]}") from None
        return {"name": core_report.CONTROL, "version": "1", "seed": int(gen.get("seed", 0)),
                "params": params}
    if name in (core_report.HOSTILE, core_report.CONTROL, core_report.WAYPOINTS, core_report.STOPS,
                core_report.MODEL_LOSS):
        if "seed" not in gen or "params" not in gen:
            raise Refused(f"declared.json's {name} generator has no seed or params")
        return {"name": name, "version": str(gen.get("version", "1")), "seed": gen["seed"],
                "params": gen["params"]}
    raise Refused(f"declared.json names generator {name!r}, which no report stream knows")


def _role(args, run: Run, generator: Mapping) -> str:
    if args.role:
        role = args.role
    elif run.simulation or run.run_mode == "shakedown":
        role = "rehearsal"
    elif run.run_mode == "control" or generator["name"] == core_report.CONTROL:
        role = "control"
    else:
        role = "test"
    if run.simulation and role != "rehearsal":
        raise Refused(f"a simulation is a rehearsal, not a {role} run (--role rehearsal)")
    if generator["name"] == core_report.CONTROL and role not in ("control", "rehearsal"):
        raise Refused(f"the control stream makes a control or rehearsal run, not a {role} run")
    if args.control_run and role == "control":
        raise Refused("a control run is not paired with another control (drop --control-run)")
    return role


# ----- the instrument's samples and clock ----------------------------------------------------------
def _clock_csv(args) -> tuple[Path | None, str]:
    """The recorder's clock.csv: --clock-csv, else the one beside a `be fit` output
    (SESSION/fit/samples.csv -> SESSION/clock.csv)."""
    if args.clock_csv:
        return Path(args.clock_csv), "--clock-csv"
    for sample in args.samples:
        p = Path(sample)
        if p.parent.name == "fit" and (p.parent.parent / "clock.csv").is_file():
            return p.parent.parent / "clock.csv", "the recording beside --samples"
    return None, ""


def instrument_samples(args, run: Run, times: timebase.RunTimes,
                       say: Callable[[str], None]) -> tuple[timebase.Clock, timebase.Converted]:
    """The samples on the run timebase, and how they got there."""
    method = args.clock
    if args.samples:
        if method is None:
            raise Refused("--samples needs --clock: monotonic (the instrument stamped this run's "
                          "host's CLOCK_MONOTONIC), wall (map the recorder's clock.csv to the "
                          "runner's wall clock) or run (already on the run timebase)")
        sources = [(Path(p).name, _read(p, "--samples")) for p in args.samples]
    else:
        own = run.path / "raw" / "samples.csv"
        feed = run.declared.get("instrument_feed") or {}
        if not own.is_file() or feed.get("kind") != "simulation_ground_truth":
            raise Refused("no instrument samples: pass --samples (be fit's samples.csv, or your "
                          "instrument's be-samples-csv/1) with --clock")
        if method not in (None, "run"):
            raise Refused(f"--clock {method} converts --samples; the runner's simulated "
                          "instrument already wrote raw/samples.csv on the run timebase")
        method = "run"
        sources = [("samples.csv", _read(own, "the run's"))]
    if args.wall_clock_agreement_s is not None and method != "wall":
        raise Refused("--wall-clock-agreement-s goes with --clock wall")
    if args.clock_csv and method == "run":
        raise Refused("--clock-csv goes with --clock monotonic or wall")
    clock_path, found_by = _clock_csv(args) if method != "run" else (None, "")
    pairs, evidence = None, None
    if clock_path is not None:
        evidence = _read(clock_path, "the recorder's clock.csv")
        try:
            pairs = timebase.read_clock_csv(evidence)
        except timebase.TimebaseError as e:
            raise Refused(f"{clock_path}: {e}") from None
        say(f"Clock: {clock_path.name} ({len(pairs)} pairs), from {found_by}.")
    try:
        if method == "monotonic":
            clock = timebase.monotonic_clock(times, pairs, evidence)
        elif method == "wall":
            if pairs is None:
                raise Refused("--clock wall needs the recorder's clock.csv (--clock-csv)")
            if args.wall_clock_agreement_s is None:
                raise Refused("--clock wall needs --wall-clock-agreement-s: how far apart the "
                              "recorder's and the runner's wall clocks can be (0 when one host "
                              "ran both; from the hosts' NTP or chrony statistics otherwise)")
            clock = timebase.wall_clock(times, pairs, args.wall_clock_agreement_s, evidence)
        else:
            clock = timebase.run_clock(by_runner=not args.samples)
        converted = timebase.convert_samples(sources, clock.offset)
    except timebase.TimebaseError as e:
        raise Refused(str(e)) from None
    return clock, converted


def _window_check(commands: list, converted: timebase.Converted, clock: timebase.Clock,
                  say: Callable[[str], None]) -> int:
    """How many valid samples fall in the scoring window; none means the clock is wrong."""
    first, last = Decimal(repr(commands[0].t_sent_s)), Decimal(repr(commands[-1].t_sent_s))
    lo, hi = first - clock.uncertainty, last + 1 + clock.uncertainty
    inside = sum(1 for t in converted.valid_times if lo <= t <= hi)
    times = converted.valid_times
    if not inside:
        span = f"{min(times)} s to {max(times)} s" if times else "no valid sample at all"
        raise Refused(f"no valid instrument sample falls in the run ({first} s to {last} s on the run "
                      f"timebase) after --clock {clock.method}: the samples span {span}. The clock "
                      "method or its inputs are wrong, or the instrument saw nothing.")
    say(f"Samples: {converted.rows} rows on the run timebase, {inside} valid ones in the scoring "
        f"window; offset {clock.offset} s, U {clock.uncertainty} s ({clock.method}).")
    return inside


# ----- packaging -----------------------------------------------------------------------------------
class Package:
    """The staging directory: every file written once, through here."""

    def __init__(self, root: Path, scrubber: Scrubber, say: Callable[[str], None]):
        self.root, self.scrubber, self.say = root, scrubber, say
        self.written: dict[str, int] = {}

    def put(self, rel: str, data: bytes) -> None:
        if rel in self.written:
            raise Refused(f"two inputs would both be {rel}")
        if core_report.classify(rel) is None:
            raise Refused(f"{rel} is not a path a run directory may hold (names: letters, digits, "
                          "'.', '_' and '-', not starting with '.')")
        if looks_like_private_key(data):
            raise Refused(f"{rel} looks like a private key; it must never be in a submission")
        if looks_like_lfs_pointer(data):
            raise Refused(f"{rel} is a Git LFS pointer, not the file")
        target = self.root / rel
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_bytes(data)
        self.written[rel] = len(data)

    def copy_identity_file(self, rel: str, data: bytes) -> None:
        """envelope.json, command-space.json, ev10-waypoints.json and the EV-02 / EV-05 plans: their
        hash identifies the setup the run used, so they go in byte for byte; what the scrubber would
        replace is reported."""
        found = self.scrubber.finds(data.decode("utf-8", "replace"))
        if found:
            what = ", ".join(f"{n} {k.replace('_', ' ')}" for k, n in sorted(found.items()))
            self.say(f"warning: {rel} mentions what looks like {what}. It is copied unchanged, "
                     "because its hash identifies what the run used; edit the file before the "
                     "next run if that is private.")
        self.put(rel, data)

    def csv(self, rel: str, data: bytes, role: str, *, compress: bool) -> bytes:
        """A raw CSV: scrubbed (never a number, never a PROTECTED column), gzipped if asked.
        Returns the uncompressed bytes written."""
        if data[:2] == b"\x1f\x8b":
            try:
                data = gzip.decompress(data)
            except (OSError, EOFError) as e:
                raise Refused(f"{rel}: not a valid gzip file: {e}") from None
        try:
            text = self.scrubber.csv_bytes(data, rel.removesuffix(".gz"), PROTECTED.get(role, ()))
        except UnicodeDecodeError:
            raise Refused(f"{rel} is not UTF-8 text") from None
        self.put(rel, gzip_bytes(text) if compress else text)
        return text

    def text_file(self, rel: str, data: bytes, where: str) -> None:
        """A file from the lab: scrubbed as JSON, CSV or text by its name, if it is text; a JPEG
        loses its metadata; anything else is copied (and named in a warning)."""
        lower = rel.lower()
        if lower.endswith((".jpg", ".jpeg")):
            try:
                data = strip_jpeg_metadata(data)
            except JpegError as e:
                raise Refused(f"{where}: {e}") from None
        elif b"\x00" in data or not _is_utf8(data):
            self.say(f"warning: {rel} is not text, so it was not scrubbed; check it holds no "
                     "hostnames, usernames, paths or addresses")
        elif lower.endswith(".json"):
            data = self.scrubber.json_bytes(data, rel)
        elif lower.endswith(".csv"):
            data = self.scrubber.csv_bytes(data, rel)
        else:
            data = self.scrubber.text_bytes(data, rel)
        self.put(rel, data)


def _is_utf8(data: bytes) -> bool:
    try:
        data.decode("utf-8")
    except UnicodeDecodeError:
        return False
    return True


def _raw(run: Run, name: str) -> Path | None:
    """raw/<name>.csv of the run directory, or its .csv.gz."""
    for candidate in (run.path / "raw" / f"{name}.csv", run.path / "raw" / f"{name}.csv.gz"):
        if candidate.is_file():
            return candidate
    return None


def _instrument_files(args, run: Run, scrubber: Scrubber) -> list[tuple[str, Path]]:
    """(submission path, source) for raw/instrument/: the run directory's own raw/instrument/,
    then each --instrument-file by its name."""
    out: list[tuple[str, Path]] = []
    own = run.path / "raw" / "instrument"
    if own.is_dir():
        for path in sorted(p for p in own.rglob("*") if p.is_file() or p.is_symlink()):
            out.append(("raw/instrument/" + path.relative_to(own).as_posix(), path))
    for name in args.instrument_file:
        p = Path(name)
        out.append((f"raw/instrument/{p.name}", p))
    for rel, source in out:
        parts = rel.split("/")
        if not all(NAME.fullmatch(part) for part in parts):
            raise Refused(f"{source}: {rel} is not a name a run directory allows (letters, digits, "
                          "'.', '_', '-'; not starting with '.'); rename it")
        if scrubber.finds(rel):
            raise Refused(f"{source}: the name {rel} holds what looks like a hostname, username or "
                          "address; rename it")
        if rel in RESERVED:
            raise Refused(f"{rel} is written by be report itself; rename {source}")
    return out


def _photo_name(path: Path, index: int, scrubber: Scrubber, used: set[str]) -> str:
    stem = path.stem
    name = f"{stem}.jpg"
    if (path.suffix.lower() not in (".jpg", ".jpeg") or not PHOTO_STEM.fullmatch(stem)
            or scrubber.finds(stem) or name in used):
        name = f"photo-{index:02d}.jpg"
    used.add(name)
    return name


