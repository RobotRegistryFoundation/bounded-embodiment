def _kit_git() -> tuple[str | None, bool | None]:
    """The kit's git commit and whether its tree is dirty, when it runs from a checkout of the
    bounded-embodiment repository; (None, None) otherwise (an installed wheel)."""
    package = Path(__file__).resolve().parent.parent
    try:
        def git(where: Path, *argv: str) -> str:
            proc = subprocess.run(["git", "-C", str(where), *argv], capture_output=True,
                                  text=True, timeout=10, check=False)
            if proc.returncode:
                raise OSError(proc.stderr.strip())
            return proc.stdout.strip()

        top = Path(git(package, "rev-parse", "--show-toplevel")).resolve()
        if top / "packages" / "kit" / "src" / package.name != package:
            return None, None
        sha = git(top, "rev-parse", "HEAD")
        dirty = bool(git(top, "status", "--porcelain", "--untracked-files=no", "--", "packages"))
    except (OSError, subprocess.SubprocessError, ValueError):
        return None, None
    return (sha if re.fullmatch(r"[0-9a-f]{40}(?:[0-9a-f]{24})?", sha) else None), dirty


def _software(run: Run, lab: Mapping) -> list[dict]:
    soft = run.declared.get("software") or {}
    entries = []
    kit = soft.get("kit") or {}
    if kit.get("version"):
        entries.append({"name": kit.get("name") or KIT_NAME, "version": str(kit["version"]),
                        "role": "runner and adapter"})
    core = soft.get("core") or {}
    if core.get("version"):
        entries.append({"name": core.get("name") or "bounded-embodiment",
                        "version": str(core["version"]), "role": "command generator"})
    lerobot = (run.declared.get("adapter") or {}).get("lerobot_version")
    if isinstance(lerobot, str) and lerobot:
        entries.append({"name": "lerobot", "version": lerobot, "role": "robot driver"})
    return entries + [dict(s) for s in lab.get("software", [])]


def declared_fields(*, run: Run, lab: Mapping, test: str, role: str, times: timebase.RunTimes,
                    clock: timebase.Clock, kid: str, space_digest: str, reproduces: str | None,
                    control_run: str | None) -> dict:
    """The report's declared members (core's report.build adds the rest)."""
    gen = generator_block(run.declared.get("generator"))
    adapter = run.declared.get("adapter") or {}
    safety = run.declared.get("safety") or {}
    runner_kit = ((run.declared.get("software") or {}).get("kit") or {}).get("version")
    if safety.get("fk_tripwire") not in ("on", "override") or not str(
            safety.get("hardware_stop") or "").strip():
        raise Refused("declared.json's safety block needs hardware_stop and fk_tripwire on|override")
    git_sha, dirty = _kit_git()
    doc: dict = {
        "method": dict(lab["method"]),
        "test": test,
        "role": role,
        "run": {"mode": "simulation" if run.simulation else "hardware",
                "started_at": times.started_at, "ended_at": times.ended_at,
                "operator": lab["operator"], "clock": clock.block()},
        "system_under_test": {"machine": dict(lab["machine"]), "gate": dict(lab["gate"]),
                              "software": _software(run, lab)},
        "adapter": {"name": str(adapter.get("adapter") or "unknown"),
                    "version": str(runner_kit or kit_version),
                    "command_space_sha256": space_digest},
        "generator": gen,
        "instruments": [dict(i) for i in lab["instruments"]],
        "safety": {"hardware_stop": str(safety["hardware_stop"]).strip(),
                   "fk_tripwire": safety["fk_tripwire"]},
        "provenance": {"kit": {"name": KIT_NAME, "version": kit_version, "git_sha": git_sha,
                               "dirty": dirty},
                       "python": platform.python_version(), "platform": platform.platform()},
        "license": "CC-BY-4.0",
        "rights_affirmed": True,
        "signer": {**lab["signer"], "kid": kid},
    }
    if reproduces:
        doc["reproduces"] = reproduces
    if control_run:
        doc["control_run"] = control_run
    return doc


def scrub_declared(scrubber: Scrubber, obj, key: str | None = None):
    """The declared fields with every string scrubbed but ids, digests and the generator's inputs
    (DECLARED_KEEP); keys are schema names and stay."""
    if key in DECLARED_KEEP:
        return obj
    if isinstance(obj, str):
        return scrubber.text(obj, "")
    if isinstance(obj, list):
        return [scrub_declared(scrubber, v) for v in obj]
    if isinstance(obj, dict):
        return {k: scrub_declared(scrubber, v, k) for k, v in obj.items()}
    return obj


# ----- the command ---------------------------------------------------------------------------------
def _staging(out: Path) -> Path:
    if out.exists() and (not out.is_dir() or any(out.iterdir())):
        raise Refused(f"{out} exists and is not an empty directory; a submission is written once")
    out.parent.mkdir(parents=True, exist_ok=True)
    return Path(tempfile.mkdtemp(prefix=f".{out.name}.partial-", dir=out.parent))


@dataclass
class Inputs:
    """What `be report` was given, checked."""

    run: Run
    lab: dict
    jwk: dict
    kid: str
    test: str
    role: str
    times: timebase.RunTimes
    reproduces: str | None
    control_run: str | None


def _inputs(args) -> Inputs:
    run = Run.load(args.run_dir)
    if args.test and args.test != run.test:
        raise Refused(f"--test {args.test}, but the run directory holds a {run.test} run")
    try:
        lab = load_lab_config(args.lab_config)
    except LabConfigError as e:
        raise Refused("the lab config is not usable:\n  " + "\n  ".join(e.problems)) from None
    jwk, kid = _signing_key(args.key)
    if run.test in PLAN_FILES and lab["method"].get("version") != TRIAL_METHOD_VERSION:
        raise Refused(f"{run.test} is defined by method version {TRIAL_METHOD_VERSION}; the lab config "
                      f"cites version {lab['method'].get('version')!r} (its method block)")
    role = _role(args, run, generator_block(run.declared.get("generator")))
    try:
        reproduces = ids.reproduces_id(args.reproduces) if args.reproduces else None
        control_run = ids.control_run_id(args.control_run) if args.control_run else None
        times = timebase.run_times(run.declared.get("timestamps"))
    except (ids.IdError, timebase.TimebaseError) as e:
        raise Refused(str(e)) from None
    return Inputs(run, lab, jwk, kid, run.test, role, times, reproduces, control_run)


def _setup_files(inp: Inputs, pkg: Package) -> str:
    """envelope.json, command-space.json (and EV-10's waypoints) as the run used them; returns
    the command space digest."""
    run = inp.run
    envelope_bytes = _read(run.path / "envelope.json", "the run's")
    space_bytes = _read(run.path / "command-space.json", "the run's")
    try:
        envelope = load_envelope(_json(envelope_bytes, "envelope.json"))
        space = load_command_space(_json(space_bytes, "command-space.json"))
    except (EnvelopeError, CommandSpaceError) as e:
        raise Refused(f"the run's setup files do not load: {e}") from None
    if (run.declared.get("envelope") or {}).get("hash") not in (None, envelope.hash):
        raise Refused("envelope.json is not the envelope the run used (its hash differs from "
                      "declared.json's)")
    if (run.declared.get("command_space") or {}).get("digest") not in (None, space.digest):
        raise Refused("command-space.json is not the command space the run used (its digest "
                      "differs from declared.json's)")
    measured = {p for inst in inp.lab["instruments"] for p in inst["measures"]}
    unknown = sorted(measured - set(envelope.points))
    if unknown:
        raise Refused(f"the lab config's instruments measure {unknown}, which the envelope does "
                      f"not declare (its points: {sorted(envelope.points)})")
    pkg.copy_identity_file("envelope.json", envelope_bytes)
    pkg.copy_identity_file("command-space.json", space_bytes)
    if inp.test == "EV-10":
        waypoints = run.path / "ev10-waypoints.json"
        if not waypoints.is_file():
            raise Refused("an EV-10 run needs ev10-waypoints.json in the run directory")
        pkg.copy_identity_file("ev10-waypoints.json", _read(waypoints, "the run's"))
    if inp.test in PLAN_FILES:
        name = PLAN_FILES[inp.test]
        if not (run.path / name).is_file():
            raise Refused(f"an {inp.test} run needs {name} in the run directory")
        data = _read(run.path / name, "the run's")
        loader = core_report.load_stop_plan if inp.test == "EV-02" else core_report.load_model_loss_plan
        try:
            plan = loader(data)
        except core_report.PlanError as e:
            raise Refused(f"the run's {name} does not load: {e}") from None
        recorded = (run.declared.get("generator") or {}).get("plan_digest")
        if recorded != plan.digest:
            raise Refused(f"{name} is not the plan the run used (its digest differs from declared.json's)")
        pkg.copy_identity_file(name, data)
    return space.digest


def _robot_files(inp: Inputs, pkg: Package) -> list:
    """raw/commands.csv.gz and raw/state.csv.gz (the runner wrote them on the run timebase);
    returns the command rows."""
    commands_path = _raw(inp.run, "commands")
    if commands_path is None:
        raise Refused("the run directory has no raw/commands.csv")
    text = pkg.csv("raw/commands.csv.gz", _read(commands_path, "the run's"), "commands",
                   compress=True)
    try:
        commands = rawdata.read_commands(text)
    except rawdata.RawDataError as e:
        raise Refused(f"the run's raw/commands.csv is not be-commands-csv/1: {e}") from None
    if not commands:
        raise Refused("the run sent no command (raw/commands.csv has no rows)")
    state = _raw(inp.run, "state")
    if state is not None:
        pkg.csv("raw/state.csv.gz", _read(state, "the run's"), "state", compress=True)
    return commands


def _instrument(args, inp: Inputs, pkg: Package, commands: list,
                say: Callable[[str], None]) -> timebase.Clock:
    """raw/samples.csv.gz on the run timebase, raw/accuracy.csv, raw/instrument/ (the lab's
    files, the recorder's clock.csv, timebase.json); returns the clock."""
    clock, converted = instrument_samples(args, inp.run, inp.times, say)
    _window_check(commands, converted, clock, say)
    pkg.csv("raw/samples.csv.gz", converted.data, "samples", compress=True)
    if args.accuracy:
        accuracy = _read(args.accuracy, "--accuracy")
        try:
            rawdata.read_accuracy(accuracy)
        except rawdata.RawDataError as e:
            raise Refused(f"--accuracy is not be-accuracy-csv/1: {e}") from None
        pkg.csv("raw/accuracy.csv", accuracy, "accuracy", compress=False)
    else:
        say("note: no --accuracy: without raw/accuracy.csv core gives INCONCLUSIVE "
            "(ACCURACY_CHECK_MISSING).")
    for rel, source in _instrument_files(args, inp.run, pkg.scrubber):
        pkg.text_file(rel, _read(source, "the instrument file"), str(source))
    if clock.evidence is not None:
        pkg.text_file(CLOCK_FILE, clock.evidence, "the recorder's clock.csv")
    record = dict(clock.record)
    record["samples"] = {"sources": [{**s, "name": pkg.scrubber.text(s["name"], TIMEBASE_FILE)}
                                     for s in converted.sources], "rows": converted.rows}
    pkg.put(TIMEBASE_FILE, (json.dumps(record, indent=2) + "\n").encode("utf-8"))
    files = {f for inst in inp.lab["instruments"] for f in inst["calibration"].get("files", [])}
    missing = sorted(files - set(pkg.written))
    if missing:
        raise Refused(f"the lab config lists calibration files the submission does not hold: "
                      f"{', '.join(missing)} (add them with --instrument-file)")
    return clock


SUPERVISION_NOTE = """## Live supervision (written by be report from the run's declared.json)

This run had no live external instrument feed. The bench supervised it with the robot's own state
only (the FK tripwire; `safety.fk_tripwire` is `on`): the external instrument recorded, and its
samples were scored after the run. Method section 6 item 4 allows supervision by the robot's state
alone; both are RECOMMENDED. The bench's start condition (section 6 item 6) was judged from the
robot's state, not from the instrument.
"""


def supervision_note(declared: Mapping) -> str | None:
    """The statement a run without a live instrument carries in notes/NOTES.md, else None."""
    feed = declared.get("instrument_feed") or {}
    if feed.get("kind") == "none" and feed.get("live_supervision") == "robot_state_only":
        return SUPERVISION_NOTE
    return None


def _notes(args, pkg: Package, declared: Mapping) -> None:
    text = b""
    if args.notes:
        notes = _read(args.notes, "--notes")
        try:
            text = pkg.scrubber.text_bytes(notes, "notes/NOTES.md")
        except UnicodeDecodeError:
            raise Refused(f"--notes {args.notes} is not UTF-8 text") from None
    note = supervision_note(declared)
    if note is not None:
        text = (text.rstrip() + b"\n\n" if text.strip() else b"") + note.encode("utf-8")
    if text:
        pkg.put("notes/NOTES.md", text)
    used: set[str] = set()
    for i, photo in enumerate(args.photo, start=1):
        try:
            data = strip_jpeg_metadata(_read(photo, "--photo"))
        except JpegError as e:
            raise Refused(f"--photo {photo}: {e}") from None
        pkg.put(f"notes/photos/{_photo_name(Path(photo), i, pkg.scrubber, used)}", data)


def _sign(declared: dict, inp: Inputs, stage: Path) -> dict:
    """Core: build (hash the files, derive every derived member), sign, write report.json, and
    verify with the key's public half."""
    try:
        built = core_report.build(declared, stage)
    except core_report.ReportError as e:
        lines = [f"{f.severity}: {f.code}{' at ' + f.where if f.where else ''}: {f.detail}"
                 for f in e.findings]
        raise Refused("core refused to build the report:\n  " + "\n  ".join(lines)) from None
    signed = core_report.sign_report(built, inp.jwk)
    (stage / core_report.REPORT_FILE).write_bytes(core_report.to_json(signed))
    public = {k: inp.jwk[k] for k in ("kty", "crv", "x")}
    result = core_report.verify(stage, {inp.kid: public})
    if not result.consistent:
        lines = [f"{f.severity}: {f.code} {f.where}: {f.detail}" for f in result.findings]
        raise Refused("the signed report is not consistent with its files:\n  " + "\n  ".join(lines))
    return signed


def _build(args, stage: Path, say: Callable[[str], None]) -> tuple[dict, str]:
    inp = _inputs(args)
    pkg = Package(stage, Scrubber(Identity.this_machine(redact=args.redact)), say)
    space_digest = _setup_files(inp, pkg)
    commands = _robot_files(inp, pkg)
    clock = _instrument(args, inp, pkg, commands, say)
    _notes(args, pkg, inp.run.declared)
    declared = declared_fields(run=inp.run, lab=inp.lab, test=inp.test, role=inp.role,
                               times=inp.times, clock=clock, kid=inp.kid,
                               space_digest=space_digest, reproduces=inp.reproduces,
                               control_run=inp.control_run)
    declared = scrub_declared(pkg.scrubber, declared)
    for line in pkg.scrubber.summary():
        say(f"Scrubbed {line}")
    for rel, size in sorted(pkg.written.items()):
        if size > WARN_FILE_BYTES:
            say(f"warning: {rel} is {size} bytes; the results repository takes 20 MiB per file")
    if sum(pkg.written.values()) > WARN_RUN_BYTES:
        say("warning: the submission is over 50 MiB, the results repository's limit per run")
    return _sign(declared, inp, stage), inp.kid


def execute_report(args, *, say: Callable[[str], None] = _stderr) -> int:
    out = Path(args.out)
    try:
        raw = (Path(args.run_dir) / "raw").resolve()
        if out.resolve() == raw or raw in out.resolve().parents:
            raise Refused("--out must not be inside the run's raw/ directory")
        stage = _staging(out)
    except Refused as e:
        say(f"be report: refused: {e}")
        return EXIT_REFUSED
    try:
        report, kid = _build(args, stage, say)
        if out.exists():
            out.rmdir()
        os.replace(stage, out)
    except Refused as e:
        shutil.rmtree(stage, ignore_errors=True)
        say(f"be report: refused: {e}")
        return EXIT_REFUSED
    except BaseException:
        shutil.rmtree(stage, ignore_errors=True)
        raise
    verdict = report["verdict"]
    codes = ", ".join(r["code"] for r in verdict.get("reasons", []))
    files = len(report["raw_data"])
    say(f"Wrote {out}: report.json and {files} files, signed with {kid}; consistent under core "
        f"{core_version}.")
    say(f"The verdict core derives from the files: {verdict['result']}" + (f" ({codes})" if codes else "")
        + f". Role {report['role']}, {report['run']['mode']}.")
    return EXIT_OK
