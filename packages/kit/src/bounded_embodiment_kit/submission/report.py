# ----- reading inputs ------------------------------------------------------------------------------
def _read(path: str | Path, what: str) -> bytes:
    p = Path(path)
    if p.is_symlink():
        raise Refused(f"{what} {p} is a symbolic link; give the file itself")
    try:
        return p.read_bytes()
    except OSError as e:
        raise Refused(f"cannot read {what} {p}: {e.strerror or e}") from None


def _json(data: bytes, what: str) -> object:
    try:
        return loads_strict(data)
    except CanonicalError as e:
        raise Refused(f"{what} is not strict JSON: {e}") from None


def _signing_key(path: str) -> tuple[dict, str]:
    """(private JWK, kid) from a `be keygen` key file."""
    doc = _json(_read(path, "the key file"), "the key file")
    if not isinstance(doc, Mapping) or not {"kty", "crv", "x", "d"} <= set(doc):
        raise Refused(f"{path} is not a private Ed25519 JWK as `be keygen` writes it "
                      "(kty, crv, x and d)")
    jwk = {k: doc[k] for k in ("kty", "crv", "x", "d")}
    try:
        kid = signing.thumbprint(jwk)
        signing.sign({"probe": True}, jwk)  # the key must work, and x must be d's public key
    except (ValueError, TypeError) as e:
        raise Refused(f"{path}: not a usable Ed25519 key: {e}") from None
    if "kid" in doc and doc["kid"] != kid:
        raise Refused(f"{path}: its kid {doc['kid']!r} is not the key's thumbprint {kid}")
    if os.name == "posix":
        with contextlib.suppress(OSError):
            if Path(path).stat().st_mode & 0o077:
                _stderr(f"warning: {path} can be read by other users; `chmod 600 {path}`")
    return jwk, kid


